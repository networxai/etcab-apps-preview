/* Merges translated batches into the dictionaries i18n.js reads:
     tools/i18n-src/<lang>/*.json  ({ "<Armenian key>": "<translation>" })  → i18n/<lang>.js
     tools/i18n-src/labels/*.json  ({ "<English label>": { "hy": …, "ru": … } }) → i18n/labels.js
   A batch never deletes a key; later files win.   node tools/i18n-build.mjs <V2 dir> */
import { readFileSync, writeFileSync, readdirSync, existsSync } from 'node:fs'
import { join } from 'node:path'
const V2 = process.argv[2]
const merge = (dir) => existsSync(dir) ? readdirSync(dir).filter((f) => f.endsWith('.json')).sort().reduce((a, f) => Object.assign(a, JSON.parse(readFileSync(join(dir, f), 'utf8'))), {}) : {}
const keep = (p) => existsSync(p) ? JSON.parse((s => s.slice(s.indexOf('{'), s.lastIndexOf('}') + 1))(readFileSync(p, 'utf8')) || '{}') : {}
for (const lang of ['ru', 'en']) {
  const p = join(V2, 'i18n', lang + '.js'), d = { ...keep(p), ...merge(join(V2, 'tools/i18n-src', lang)) }
  /* A translation must carry the same number of {#} as its key, or numbers would land in the wrong place. */
  const drop = existsSync(join(V2, 'tools/i18n-src/drop.json')) ? JSON.parse(readFileSync(join(V2, 'tools/i18n-src/drop.json'), 'utf8')).keys : []
  for (const k of drop) delete d[k]
  for (const [k, v] of Object.entries(d)) if ((k.match(/\{#\}/g) || []).length !== (v.match(/\{#\}/g) || []).length) { console.warn(lang, 'placeholder mismatch, dropped:', k, '→', v); delete d[k] }
  writeFileSync(p, '/* Generated by tools/i18n-build.mjs from tools/i18n-src/' + lang + ' — edit the batches, not this file. */\nwindow.I18N_DICT = ' + JSON.stringify(d) + '\n')
  console.log(lang, Object.keys(d).length)
}
const lp = join(V2, 'i18n', 'labels.js'), l = { ...keep(lp), ...merge(join(V2, 'tools/i18n-src', 'labels')) }
writeFileSync(lp, '/* Generated by tools/i18n-build.mjs. English app-state labels → hy / ru for the viewer. */\nwindow.I18N_LABELS = ' + JSON.stringify(l) + '\n')
console.log('labels', Object.keys(l).length)
